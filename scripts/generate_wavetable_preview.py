#!/usr/bin/env python3
"""Build compact waveform preview data for the Remote UI from the CC0 tables."""

import base64
from pathlib import Path
import struct
import wave


BANKS = (
    ("Harmonic", "HARMONIC.WAV"),
    ("Microwave 2", "MICROW02.WAV"),
    ("Bell 03", "BELL03.WAV"),
    ("VoxSynth", "VOXSYNTH.WAV"),
    ("Spectral", "SPECTRAL.WAV"),
    ("SuperSaw", "SUPERSAW.WAV"),
    ("Fourier 2", "FOURIER2.WAV"),
    ("Noise Wave", "NOISE_WA.WAV"),
    ("Folding", "FOLDING_.WAV"),
    ("Drone", "DRONE.WAV"),
    ("Sitar", "SITAR.WAV"),
    ("Tidal", "TIDAL.WAV"),
    ("Harmonix", "HARMONIX.WAV"),
    ("Morphing", "MORPHING.WAV"),
    ("Wavetrip", "WAVETRIP.WAV"),
    ("Sine to Saw", "SINE2SAW.WAV"),
    ("Saw Bend", "SAW_BEND.WAV"),
    ("Basic Morph", "BASIC_WA.WAV"),
    ("Tidy 006", "TIDYB006.WAV"),
    ("AM Sine", "AM_SINE.WAV"),
    ("Hmmm", "HMMMMMMM.WAV"),
    ("Iterative", "ITERATIV.WAV"),
    ("Osmaos", "OSMAOS.WAV"),
    ("Twist 02", "TWIST02.WAV"),
    ("Sine Mutate", "SINE_MUT.WAV"),
    ("Reso 00", "RESO_P00.WAV"),
    ("Sohler 34", "SOHLER34.WAV"),
    ("Sohler 35", "SOHLER35.WAV"),
    ("PD 101", "PD101.WAV"),
    ("Sohler 43", "SOHLER43.WAV"),
    ("Mellow D", "MELLOW_D.WAV"),
    ("Tidy 007", "TIDYB007.WAV"),
)
TABLE_SIZE = 256
FRAMES = 64
PREVIEW_POINTS = 128
ASSET_DIR = Path(__file__).resolve().parents[1] / "assets" / "wavetables" / "wavedit-online"


def encode_bank(filename: str) -> str:
    with wave.open(str(ASSET_DIR / filename), "rb") as source:
        if (source.getnchannels(), source.getsampwidth(), source.getnframes()) != (
            1, 2, FRAMES * TABLE_SIZE
        ):
            raise ValueError(f"{filename}: expected mono 16-bit PCM with {FRAMES * TABLE_SIZE} samples")
        raw = source.readframes(source.getnframes())

    samples = [sample[0] / 32768.0 for sample in struct.iter_unpack("<h", raw)]
    preview = bytearray()
    for frame in range(FRAMES):
        cycle = samples[frame * TABLE_SIZE:(frame + 1) * TABLE_SIZE]
        peak = max((abs(value) for value in cycle), default=0.0)
        if peak < 1e-12:
            preview.extend([128] * PREVIEW_POINTS)
            continue
        for point in range(PREVIEW_POINTS):
            position = point * TABLE_SIZE / PREVIEW_POINTS
            index = int(position)
            fraction = position - index
            a = cycle[index]
            b = cycle[(index + 1) % TABLE_SIZE]
            value = (a + (b - a) * fraction) / peak
            preview.append(max(0, min(255, round(128 + value * 120))))
    return base64.b64encode(preview).decode("ascii")


def render() -> str:
    names = ",\n  ".join('"%s"' % name for name, _ in BANKS)
    data = ",\n  ".join('"%s"' % encode_bank(filename) for _, filename in BANKS)
    return """/* Generated by scripts/generate_wavetable_preview.py; do not edit. */
(function (root) {
  var encoded = [
  %s
  ];
  root.SF_WAVETABLE_PREVIEW = {
    frames: %d,
    points: %d,
    names: [
  %s
    ],
    banks: encoded.map(function (text) {
      var binary = atob(text);
      var samples = new Uint8Array(binary.length);
      for (var i = 0; i < binary.length; i++) samples[i] = binary.charCodeAt(i);
      return samples;
    })
  };
}(window));
""" % (data, FRAMES, PREVIEW_POINTS, names)


def main() -> None:
    import sys

    if len(sys.argv) != 2:
        raise SystemExit("usage: generate_wavetable_preview.py OUTPUT_JS")
    output = Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
